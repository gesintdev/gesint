-- Historico de alteracoes (Hibernate Envers) para as entidades com CRUD.
--
-- revinfo            : uma linha por transacao (quem e quando).
-- <tabela>_aud       : estado completo da linha a cada revisao + rev + revtype
--                      (0 = insert, 1 = update, 2 = delete fisico). Soft delete e um update
--                      com status = DELETED.
--
-- Tabela nova com CRUD (ou coluna nova em tabela auditada) deve chamar, na propria migration:
--   SELECT public.gesint_audit_sync_table('<tabela>');
-- A funcao cria/alinha <tabela>_aud em public e em todos os schemas de cliente. O Admin
-- replica as tabelas *_aud e revinfo de public ao provisionar/sincronizar tenants.

-- 1) Auditoria Spring em role (perfis): so tinha created_at/updated_at.
ALTER TABLE role
    ADD COLUMN IF NOT EXISTS created_by UUID,
    ADD COLUMN IF NOT EXISTS updated_by UUID;

-- 2) Revisao Envers. Identity (e nao serial) para que LIKE ... INCLUDING ALL crie uma sequence
--    propria em cada schema de cliente.
CREATE TABLE IF NOT EXISTS revinfo (
    rev         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    changed_at  TIMESTAMPTZ NOT NULL,
    changed_by  UUID
);

CREATE INDEX IF NOT EXISTS idx_revinfo_changed_at ON revinfo (changed_at);

-- 3) Copia colunas ausentes e alinha tipos de template -> alvo. Sem defaults nem NOT NULL:
--    revisoes de delete gravam apenas a chave.
CREATE OR REPLACE FUNCTION public.gesint_audit_copy_columns(
    p_template regclass,
    p_target_schema text,
    p_target_table text)
RETURNS void
LANGUAGE plpgsql
AS $fn$
DECLARE
    target_rel regclass := to_regclass(format('%I.%I', p_target_schema, p_target_table));
    col record;
BEGIN
    FOR col IN
        SELECT a.attname, format_type(a.atttypid, a.atttypmod) AS col_type
        FROM pg_attribute a
        WHERE a.attrelid = p_template
          AND a.attnum > 0
          AND NOT a.attisdropped
          AND NOT EXISTS (
              SELECT 1
              FROM pg_attribute t
              WHERE t.attrelid = target_rel
                AND t.attname = a.attname
                AND NOT t.attisdropped)
        ORDER BY a.attnum
    LOOP
        EXECUTE format('ALTER TABLE %I.%I ADD COLUMN %I %s',
                p_target_schema, p_target_table, col.attname, col.col_type);
    END LOOP;

    FOR col IN
        SELECT a.attname, format_type(a.atttypid, a.atttypmod) AS col_type
        FROM pg_attribute a
        JOIN pg_attribute t
          ON t.attrelid = target_rel
         AND t.attname = a.attname
         AND NOT t.attisdropped
        WHERE a.attrelid = p_template
          AND a.attnum > 0
          AND NOT a.attisdropped
          AND (a.atttypid, a.atttypmod) IS DISTINCT FROM (t.atttypid, t.atttypmod)
    LOOP
        EXECUTE format('ALTER TABLE %I.%I ALTER COLUMN %I TYPE %s USING %I::text::%s',
                p_target_schema, p_target_table, col.attname, col.col_type, col.attname, col.col_type);
    END LOOP;
END
$fn$;

-- 4) Cria/alinha <tabela>_aud em public a partir da tabela base e replica para todos os schemas
--    de cliente (schemas com app_user/permission, exceto public/admin/gesint_types/pg_*).
CREATE OR REPLACE FUNCTION public.gesint_audit_sync_table(p_table text)
RETURNS void
LANGUAGE plpgsql
AS $fn$
DECLARE
    aud_table   text := p_table || '_aud';
    base_rel    regclass := to_regclass(format('public.%I', p_table));
    aud_rel     regclass;
    key_columns text;
    col         record;
    tenant      text;
BEGIN
    IF base_rel IS NULL THEN
        RAISE EXCEPTION 'gesint_audit_sync_table: tabela public.% nao existe', p_table;
    END IF;

    IF to_regclass(format('public.%I', aud_table)) IS NULL THEN
        EXECUTE format('CREATE TABLE public.%I (LIKE public.%I)', aud_table, p_table);
        EXECUTE format('ALTER TABLE public.%I ADD COLUMN rev BIGINT NOT NULL, ADD COLUMN revtype SMALLINT',
                aud_table);
    END IF;
    aud_rel := to_regclass(format('public.%I', aud_table));

    PERFORM public.gesint_audit_copy_columns(base_rel, 'public', aud_table);

    FOR col IN
        SELECT a.attname
        FROM pg_attribute a
        WHERE a.attrelid = aud_rel
          AND a.attnum > 0
          AND NOT a.attisdropped
          AND a.attnotnull
          AND a.attname <> 'rev'
          AND NOT EXISTS (
              SELECT 1
              FROM pg_index i
              WHERE i.indrelid = aud_rel
                AND i.indisprimary
                AND a.attnum = ANY (i.indkey))
    LOOP
        EXECUTE format('ALTER TABLE public.%I ALTER COLUMN %I DROP NOT NULL', aud_table, col.attname);
    END LOOP;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = aud_rel AND contype = 'p') THEN
        IF EXISTS (
            SELECT 1 FROM pg_attribute
            WHERE attrelid = base_rel AND attname = 'id' AND NOT attisdropped) THEN
            key_columns := 'id';
        ELSE
            SELECT string_agg(quote_ident(a.attname), ', ' ORDER BY k.ord)
              INTO key_columns
              FROM pg_index i
              CROSS JOIN LATERAL unnest(i.indkey) WITH ORDINALITY AS k(attnum, ord)
              JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = k.attnum
             WHERE i.indrelid = base_rel
               AND i.indisprimary;
        END IF;
        IF key_columns IS NULL THEN
            RAISE EXCEPTION 'gesint_audit_sync_table: public.% sem coluna id nem chave primaria', p_table;
        END IF;
        EXECUTE format('ALTER TABLE public.%I ADD PRIMARY KEY (%s, rev)', aud_table, key_columns);
    END IF;

    EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON public.%I (rev)', 'idx_' || aud_table || '_rev', aud_table);

    FOR tenant IN
        SELECT n.nspname
        FROM pg_namespace n
        WHERE n.nspname NOT IN ('public', 'admin', 'gesint_types', 'information_schema')
          AND n.nspname NOT LIKE 'pg\_%' ESCAPE '\'
          AND (to_regclass(format('%I.app_user', n.nspname)) IS NOT NULL
               OR to_regclass(format('%I.permission', n.nspname)) IS NOT NULL)
        ORDER BY 1
    LOOP
        IF to_regclass(format('%I.revinfo', tenant)) IS NULL THEN
            EXECUTE format('CREATE TABLE %I.revinfo (LIKE public.revinfo INCLUDING ALL)', tenant);
        END IF;

        IF to_regclass(format('%I.%I', tenant, aud_table)) IS NULL THEN
            EXECUTE format('CREATE TABLE %I.%I (LIKE public.%I INCLUDING ALL)', tenant, aud_table, aud_table);
        ELSE
            PERFORM public.gesint_audit_copy_columns(aud_rel, tenant, aud_table);
        END IF;
    END LOOP;
END
$fn$;

-- 5) Tenants existentes: colunas novas de role.
DO $sync_role_audit_columns$
DECLARE
    target_schema text;
BEGIN
    FOR target_schema IN
        SELECT n.nspname
        FROM pg_namespace n
        WHERE n.nspname NOT IN ('public', 'admin', 'gesint_types', 'information_schema')
          AND n.nspname NOT LIKE 'pg\_%' ESCAPE '\'
          AND to_regclass(format('%I.role', n.nspname)) IS NOT NULL
        ORDER BY 1
    LOOP
        EXECUTE format(
            'ALTER TABLE %I.role ADD COLUMN IF NOT EXISTS created_by UUID, ADD COLUMN IF NOT EXISTS updated_by UUID',
            target_schema);
    END LOOP;
END
$sync_role_audit_columns$;

